// Сид-able генератор случайных чисел. Один и тот же сид → ровно та же партия:
// та же карта, расположение ресурсов и декора, состав и заход волн. Это даёт
// воспроизводимость — поймал баг, записал сид, повторил ту же ситуацию — и
// стабильные (не «мигающие») тесты.
//
// Здесь живёт только ИГРОВАЯ случайность, влияющая на ход партии (генерация карты,
// волны). Чисто визуальный/звуковой рандом (частицы, шанс звука удара) оставлен на
// Math.random: он не меняет состояние игры и не должен сбивать воспроизводимый поток.
//
// Алгоритм — mulberry32: крошечный, быстрый, детерминированный PRNG (32-битное состояние).

let state = 0 >>> 0;
let seed = 0 >>> 0;

// Задать сид — обнуляет поток. Вызывается в начале партии (main.startGame).
export function seedRng(s: number): void {
  seed = s >>> 0;
  state = seed;
}
// Текущий сид партии (для лога/воспроизведения/будущих сохранений).
export function getSeed(): number { return seed; }

// Следующее псевдослучайное число в [0, 1) — замена Math.random().
export function rng(): number {
  state = (state + 0x6d2b79f5) | 0;
  let t = Math.imul(state ^ (state >>> 15), 1 | state);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

// Целое в [0, n).
export function rndInt(n: number): number { return (rng() * n) | 0; }
// Случайный элемент массива.
export function pick<T>(arr: T[]): T { return arr[(rng() * arr.length) | 0]; }

// Сид по умолчанию: поток определён ещё до явного seedRng (важно для модулей,
// дёргающих rng при загрузке, и для тестов без явной инициализации).
seedRng(1);
